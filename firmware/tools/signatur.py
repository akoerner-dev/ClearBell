"""ClearBell V0.2 - signed updates (port step 10d, R26). Called through cb.py:

    python tools/cb.py schluessel-erzeugen              ONCE per manufacturer: main + spare key, writes the public
                                                        key digests into components/cb_core/include/cb_update_keys.h
    python tools/cb.py signieren aussen|innen|alle      sign the built image(s) with the main key
    python tools/cb.py signieren innen --ersatz         ... with the spare key (only if the main key is lost)
    python tools/cb.py besitzer-schluessel <key.pem>    key digest of an OWN key (for the buyer's page, R26)
    python tools/cb.py signatur-testvektor              regenerate the test vector (throwaway keys) - rarely needed

Keys: RSA-3072, ESP-IDF Secure Boot v2 format, made and used by espsecure.py (part of ESP-IDF). The private keys
live in <ClearBell project folder>/Geheimnisse/signatur/ - never in the repository. The SPARE key belongs OFFLINE
(USB stick and paper copy in two places) and is deleted from the PC after the copies are checked; it is only
needed when the main key is lost or known to others. Losing BOTH is not the end: every unit still accepts an own
key entered in maintenance mode (R26), it just takes one visit per unit.

Output of signieren: <build>/<unit>/clearbell-signiert.bin (what `cb.py update` uploads) and a copy named
clearbell-<version>-<unit>.bin for a release page.
"""

import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

FIRMWARE = Path(__file__).resolve().parents[1]
GEHEIM = Path(os.environ.get("CB_GEHEIM", FIRMWARE.parents[1] / "Geheimnisse")) / "signatur"
KEYS_HEADER = FIRMWARE / "components" / "cb_core" / "include" / "cb_update_keys.h"
VECTOR_HEADER = FIRMWARE / "components" / "cb_core" / "include" / "cb_update_sig_vector.h"
MAIN, SPARE = GEHEIM / "hersteller_haupt.pem", GEHEIM / "hersteller_ersatz.pem"
SECTOR, BLOCK = 4096, 1216


def _espsecure(py: Path, *args: str) -> None:
    subprocess.check_call([str(py), "-m", "espsecure", *args], stdout=subprocess.DEVNULL)


def _key_digest(py: Path, pem: Path) -> bytes:
    """The official Secure Boot v2 key digest (the value stage C would burn into the eFuse)."""
    with tempfile.TemporaryDirectory() as t:
        out = Path(t) / "d.bin"
        _espsecure(py, "digest_sbv2_public_key", "--keyfile", str(pem), "--output", str(out))
        return out.read_bytes()


def _c_bytes(b: bytes, indent: str = "    ", per_line: int = 16) -> str:
    lines = [", ".join(f"0x{x:02x}" for x in b[i:i + per_line]) for i in range(0, len(b), per_line)]
    return (",\n" + indent).join(lines)


def schluessel_erzeugen(py: Path) -> int:
    if MAIN.exists() or SPARE.exists() or KEYS_HEADER.exists():
        print(f"refused: keys exist already ({GEHEIM} or {KEYS_HEADER.name}).\n"
              "New manufacturer keys would lock every unit built so far out of updates - never do this lightly.")
        return 1
    GEHEIM.mkdir(parents=True, exist_ok=True)
    for pem in (MAIN, SPARE):
        _espsecure(py, "generate_signing_key", "--version", "2", "--scheme", "rsa3072", str(pem))
    d = [_key_digest(py, MAIN), _key_digest(py, SPARE)]
    KEYS_HEADER.write_text(
        "// cb_update_keys.h - GENERATED by `tools/cb.py schluessel-erzeugen` (tools/signatur.py). Public, not secret.\n"
        "//\n"
        "// The two manufacturer key digests every ClearBell firmware trusts for updates (R26, cb_update_sig.h):\n"
        "// SHA-256 over the RSA-3072 public key in Secure Boot v2 encoding, as `espsecure.py digest_sbv2_public_key`\n"
        "// prints it. [0] = main key (signs every release), [1] = spare key (kept offline, only if [0] is lost).\n"
        "// NEVER replace these in a release: units only accept updates signed with keys they already know. To retire\n"
        "// a key, sign one release with the other key that no longer lists it.\n"
        "#pragma once\n\n#include <cstdint>\n\nnamespace cb {\n\n"
        "static constexpr uint8_t kMakerKeyDigest[2][32] = {\n"
        f"    {{{_c_bytes(d[0], ' ' * 5)}}},  // main  {d[0][:8].hex()}\n"
        f"    {{{_c_bytes(d[1], ' ' * 5)}}},  // spare {d[1][:8].hex()}\n"
        "};\n\n}  // namespace cb\n", encoding="utf-8", newline="\n")
    print(f"main key:  {MAIN}\n           digest {d[0].hex()}")
    print(f"spare key: {SPARE}\n           digest {d[1].hex()}")
    print(f"header:    {KEYS_HEADER}")
    print("\nNEXT: copy BOTH .pem files to a USB stick and print them (two places), check the copies, then DELETE\n"
          "the spare key from the PC. Rebuild: the digests are part of every firmware from now on.")
    return 0


def _image_version(image: bytes) -> str:
    """The version the IMAGE carries (esp_app_desc_t.version at offset 48), e.g. "0.2.0-dev+innen" - what the unit
    will report. Taken from the image, not from version.txt, so the release name can never disagree with it."""
    if len(image) < 80 or image[0] != 0xE9 or int.from_bytes(image[32:36], "little") != 0xABCD5432:
        raise SystemExit("not an ESP-IDF app image")
    return image[48:80].split(b"\0", 1)[0].decode("ascii", "replace")


def signieren(unit: str, py: Path, build_root: Path, spare: bool = False) -> int:
    key = SPARE if spare else MAIN
    if not key.exists():
        print(f"signing key missing: {key}" + ("" if spare else "  (cb.py schluessel-erzeugen, or copy it back)"))
        return 2
    src = build_root / unit / "clearbell.bin"
    if not src.exists():
        print(f"no image: {src} - build first (cb.py bauen {unit})")
        return 2
    out = build_root / unit / "clearbell-signiert.bin"
    _espsecure(py, "sign_data", "--version", "2", "--keyfile", str(key), "--output", str(out), str(src))
    data = out.read_bytes()
    blk = data[-SECTOR:-SECTOR + BLOCK]
    assert blk[0] == 0xE7 and blk[4:36] == hashlib.sha256(data[:-SECTOR]).digest(), "signature block not as expected"
    version = _image_version(data)
    core, _, img_unit = version.partition("+")
    if img_unit != unit:
        raise SystemExit(f"image says unit '{img_unit}', expected '{unit}' - wrong build directory?")
    release = build_root / unit / f"clearbell-{core}-{unit}.bin"
    shutil.copyfile(out, release)
    kd = hashlib.sha256(blk[36:812]).digest()
    print(f"{unit}: {version} signed with the {'SPARE' if spare else 'main'} key {kd[:8].hex()} -> {out.name} "
          f"({len(data)} B), release copy {release.name}")
    return 0


def besitzer_schluessel(py: Path, pem: str) -> int:
    d = _key_digest(py, Path(pem))
    print(f"key digest of {pem}:\n{d.hex()}\n"
          "Enter it on the unit's status page in maintenance mode (Einstellungen -> Update-Schlüssel).")
    return 0


def testvektor(py: Path) -> int:
    """Two throwaway keys sign a fixed 4096-byte pattern. Only public data goes into the header; the keys are
    deleted at once - the vector can never be used to sign anything else."""
    with tempfile.TemporaryDirectory() as t:
        t = Path(t)
        image = bytes((i * 31 + 7) & 0xFF for i in range(SECTOR))
        (t / "img.bin").write_bytes(image)
        for k in ("a", "b"):
            _espsecure(py, "generate_signing_key", "--version", "2", "--scheme", "rsa3072", str(t / f"{k}.pem"))
        _espsecure(py, "sign_data", "--version", "2", "--keyfile", str(t / "a.pem"), str(t / "b.pem"),
                   "--output", str(t / "signed.bin"), str(t / "img.bin"))
        signed = (t / "signed.bin").read_bytes()
        da, db = _key_digest(py, t / "a.pem"), _key_digest(py, t / "b.pem")
    assert signed[:SECTOR] == image and len(signed) == 2 * SECTOR
    blocks = signed[SECTOR:SECTOR + 2 * BLOCK]
    digest = hashlib.sha256(image).digest()
    assert blocks[4:36] == digest and blocks[BLOCK + 4:BLOCK + 36] == digest
    assert hashlib.sha256(blocks[36:812]).digest() == da, "key digest = SHA-256 over bytes 36..811"
    VECTOR_HEADER.write_text(
        "// cb_update_sig_vector.h - GENERATED by `tools/cb.py signatur-testvektor` (tools/signatur.py).\n"
        "//\n"
        "// Known-answer vector for cb::sig_selftest(): a 4096-byte pattern signed by espsecure.py (Secure Boot v2,\n"
        "// RSA-3072) with two THROWAWAY keys A and B that were deleted right after - they are trusted nowhere.\n"
        "#pragma once\n\n#include <cstddef>\n#include <cstdint>\n\nnamespace cb {\n\n"
        f"static constexpr size_t kSigVecImageLen = {SECTOR};\n"
        "inline uint8_t sig_vec_image_byte(size_t i) { return (uint8_t)(i * 31u + 7u); }\n\n"
        f"static constexpr uint8_t kSigVecImageDigest[32] = {{\n    {_c_bytes(digest)}}};\n\n"
        f"static constexpr uint8_t kSigVecKeyA[32] = {{\n    {_c_bytes(da)}}};\n\n"
        f"static constexpr uint8_t kSigVecKeyB[32] = {{\n    {_c_bytes(db)}}};\n\n"
        f"// block 1 (key A), block 2 (key B), {BLOCK} bytes each\n"
        f"static constexpr uint8_t kSigVecBlocks[{2 * BLOCK}] = {{\n    {_c_bytes(blocks)}}};\n\n"
        "}  // namespace cb\n", encoding="utf-8", newline="\n")
    print(f"written: {VECTOR_HEADER}")
    return 0


if __name__ == "__main__":
    print(__doc__)
    sys.exit(0)
